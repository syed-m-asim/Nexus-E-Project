using System.ComponentModel.DataAnnotations;
using Microsoft.AspNetCore.Mvc.ModelBinding;
using Microsoft.AspNetCore.Mvc.ModelBinding.Validation;

namespace NexusCommunication.Models;

/// <summary>
/// An application for one or more connections. OrderNumber is 11 chars: type letter + 10-digit serial (D0000000001).
/// Properties that are filled in by the server (order number, status, discount, counters) are protected with
/// [BindNever] so that a user cannot over-post them through a hand-made form request.
/// Database-dependent rules (does the plan exist, is it the right type ...) live in Helpers/OrderValidation.cs.
/// </summary>
public class Order : IValidatableObject
{
    public int Id { get; set; }

    /// <summary>Generated by the server when the order is placed (never typed by the user).</summary>
    [BindNever, ValidateNever]
    [MaxLength(11)] public string OrderNumber { get; set; } = "";

    [Range(1, int.MaxValue, ErrorMessage = "Please select a customer.")]
    public int CustomerId { get; set; }
    public Customer? Customer { get; set; }

    [Range(1, int.MaxValue, ErrorMessage = "Please select a city.")]
    public int CityId { get; set; }
    public City? City { get; set; }

    /// <summary>Address where the connection has to be installed.</summary>
    [Required(ErrorMessage = "Installation address is required.")]
    [MinLength(5, ErrorMessage = "Installation address must be at least 5 characters long.")]
    [MaxLength(300, ErrorMessage = "Installation address cannot be longer than 300 characters.")]
    [Display(Name = "Installation Address")]
    public string InstallationAddress { get; set; } = "";

    [Range(1, int.MaxValue, ErrorMessage = "Please select a retail store.")]
    public int RetailStoreId { get; set; }
    public RetailStore? RetailStore { get; set; }

    /// <summary>Set by the server (never posted by the browser).</summary>
    [BindNever]
    public int PlacedByEmployeeId { get; set; }

    [EnumDataType(typeof(ConnectionType), ErrorMessage = "Select a valid connection type.")]
    [Display(Name = "Connection Type")]
    public ConnectionType ConnectionType { get; set; }

    /// <summary>The plan of the requested connection (internet plan for dial-up / broadband, phone plan for telephone).</summary>
    [Range(1, int.MaxValue, ErrorMessage = "Please select a plan.")]
    public int PlanId { get; set; }
    public Plan? Plan { get; set; }

    /// <summary>Dial-up only: plan for a NEW landline applied together with the internet connection.</summary>
    public int? LandlinePlanId { get; set; }
    public Plan? LandlinePlan { get; set; }

    /// <summary>Dial-up only: customer already holds a landline from the same vendor (internet feasibility only).</summary>
    public int? ExistingLandlineConnectionId { get; set; }

    /// <summary>Modem / router chosen by the customer.</summary>
    public int? EquipmentProductId { get; set; }
    public Product? EquipmentProduct { get; set; }

    /// <summary>How many connections are requested in this order (bulk / corporate orders have more than one).</summary>
    [Range(1, 1000, ErrorMessage = "Number of connections must be between 1 and 1000.")]
    [Display(Name = "Number of Connections")]
    public int NumberOfConnections { get; set; } = 1;

    /// <summary>Bulk discount decided at order time from the number of connections (server calculated).</summary>
    [BindNever]
    public decimal BulkDiscountPercent { get; set; }

    /// <summary>Number of connections already created for this order (server maintained).</summary>
    [BindNever]
    public int ConnectionsProvided { get; set; }

    /// <summary>Workflow status of the order (server maintained, changed by the technical team).</summary>
    [BindNever]
    public OrderStatus Status { get; set; } = OrderStatus.Placed;

    [BindNever]
    public DateTime PlacedOn { get; set; } = DateTime.UtcNow;

    [MaxLength(500, ErrorMessage = "Remarks cannot be longer than 500 characters.")]
    public string? Remarks { get; set; }

    public List<FeasibilityCheck> FeasibilityChecks { get; set; } = new();

    /// <summary>Cross-field rules that do not need the database.</summary>
    public IEnumerable<ValidationResult> Validate(ValidationContext validationContext)
    {
        // A dial-up connection needs a landline of the same vendor: either an existing one or a new one.
        if (ConnectionType == ConnectionType.DialUp && !LandlinePlanId.HasValue && !ExistingLandlineConnectionId.HasValue)
        {
            yield return new ValidationResult(
                "A dial-up connection needs a landline: choose an existing landline account or a new landline plan.",
                new[] { nameof(LandlinePlanId), nameof(ExistingLandlineConnectionId) });
        }

        // A dial-up customer either already has a landline or applies for a new one - never both.
        if (ConnectionType == ConnectionType.DialUp && LandlinePlanId.HasValue && ExistingLandlineConnectionId.HasValue)
        {
            yield return new ValidationResult(
                "Choose either a new landline plan or an existing landline account, not both.",
                new[] { nameof(LandlinePlanId), nameof(ExistingLandlineConnectionId) });
        }
    }
}
